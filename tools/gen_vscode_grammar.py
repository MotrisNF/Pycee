#!/usr/bin/env python3
"""
Writes editors/vscode/syntaxes/pycee.tmLanguage.json, the highlighting
grammar of the VS Code extension. The global natives, the error types and
the modules come from include/resolver/natives.h, so the grammar follows
the language: run this again after changing that file.

    python3 tools/gen_vscode_grammar.py
"""

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(ROOT, "include/resolver/natives.h")) as f:
    header = f.read()

native_list = header[header.index("# define NATIVE_LIST(X)"):
                     header.index("# define NATIVE_MODULES(M)")]
globals_ = re.findall(r"X\((\w+),", native_list)
errors = [n for n in globals_ if n.endswith("Error") or n == "KeyboardInterrupt"]
functions = [n for n in globals_ if n not in errors]
modules = re.findall(r"M\((\w+)\)", header[header.index("# define NATIVE_MODULES(M)"):
                                           header.index("# define NATIVE_MEMBERS")])


def words(names):
    return r"\b(" + "|".join(names) + r")\b"


ESCAPES = {
    "name": "constant.character.escape.pycee",
    "match": r"\\(n|t|r|0|\"|'|\\|x[0-9A-Fa-f]{2}|u\{[0-9A-Fa-f]+\})",
}
BAD_ESCAPE = {"name": "invalid.illegal.escape.pycee", "match": r"\\."}


def string(begin, end, name, escapes=True, fmt=False):
    patterns = []
    if fmt:
        patterns += [
            {"name": "constant.character.escape.pycee", "match": r"\{\{|\}\}"},
            {
                "name": "meta.embedded.expression.pycee",
                "begin": r"\{",
                "end": r"\}",
                "beginCaptures": {"0": {"name": "punctuation.section.embedded.begin.pycee"}},
                "endCaptures": {"0": {"name": "punctuation.section.embedded.end.pycee"}},
                "contentName": "source.pycee",
                "patterns": [
                    {"name": "constant.other.format-spec.pycee",
                     "match": r":[<>^=+\- #0-9,_.a-zA-Z%]*(?=\})"},
                    {"include": "#expression"},
                ],
            },
        ]
    if escapes:
        patterns += [ESCAPES, BAD_ESCAPE]
    return {
        "name": name,
        "begin": begin,
        "end": end,
        "beginCaptures": {"0": {"name": "punctuation.definition.string.begin.pycee"}},
        "endCaptures": {"0": {"name": "punctuation.definition.string.end.pycee"}},
        "patterns": patterns,
    }


grammar = {
    "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    "name": "pycee",
    "scopeName": "source.pycee",
    "comment": "Generated by tools/gen_vscode_grammar.py: do not edit by hand.",
    "patterns": [{"include": "#statement"}],
    "repository": {
        "statement": {
            "patterns": [
                {"include": "#comments"},
                {"include": "#import"},
                {"include": "#declarations"},
                {"include": "#expression"},
            ]
        },
        "comments": {
            "patterns": [
                {
                    "name": "comment.block.pycee",
                    "begin": r"/\*",
                    "end": r"\*/",
                    "captures": {"0": {"name": "punctuation.definition.comment.pycee"}},
                },
                {
                    "name": "comment.line.number-sign.pycee",
                    "match": r"(#).*$",
                    "captures": {"1": {"name": "punctuation.definition.comment.pycee"}},
                },
            ]
        },
        "import": {
            "patterns": [
                {
                    "match": r"\b(import)\s+([A-Za-z_]\w*)(?:\s+(as)\s+([A-Za-z_]\w*))?",
                    "captures": {
                        "1": {"name": "keyword.control.import.pycee"},
                        "2": {"name": "entity.name.namespace.pycee"},
                        "3": {"name": "keyword.control.import.pycee"},
                        "4": {"name": "entity.name.namespace.pycee"},
                    },
                },
                {
                    "match": r"\b(from)\s+([A-Za-z_]\w*)\s+(import)\b",
                    "captures": {
                        "1": {"name": "keyword.control.import.pycee"},
                        "2": {"name": "entity.name.namespace.pycee"},
                        "3": {"name": "keyword.control.import.pycee"},
                    },
                },
            ]
        },
        "declarations": {
            "patterns": [
                {
                    "match": r"\b(func|prog)\s+([A-Za-z_]\w*)",
                    "captures": {
                        "1": {"name": "storage.type.function.pycee"},
                        "2": {"name": "entity.name.function.pycee"},
                    },
                },
                {
                    "match": r"\b(obj)\s+([A-Za-z_]\w*)(?:\s+(extends)\s+([A-Za-z_]\w*)|\s*\(\s*([A-Za-z_]\w*)\s*\))?",
                    "captures": {
                        "1": {"name": "storage.type.class.pycee"},
                        "2": {"name": "entity.name.type.class.pycee"},
                        "3": {"name": "storage.modifier.pycee"},
                        "4": {"name": "entity.other.inherited-class.pycee"},
                        "5": {"name": "entity.other.inherited-class.pycee"},
                    },
                },
                {
                    "match": r"\b(var|vemp|const)\s+([A-Za-z_]\w*)",
                    "captures": {
                        "1": {"name": "storage.type.pycee"},
                        "2": {"name": "variable.other.declaration.pycee"},
                    },
                },
            ]
        },
        "expression": {
            "patterns": [
                {"include": "#comments"},
                {"include": "#strings"},
                {"include": "#numbers"},
                {"include": "#keywords"},
                {"include": "#builtins"},
                {"include": "#calls"},
                {"include": "#operators"},
                {"include": "#punctuation"},
            ]
        },
        "strings": {
            "patterns": [
                string(r'[fF]"""', '"""', "string.quoted.triple.interpolated.pycee", fmt=True),
                string(r'[rR]"""', '"""', "string.quoted.triple.raw.pycee", escapes=False),
                string('"""', '"""', "string.quoted.triple.pycee"),
                string(r'[fF]"', '"', "string.quoted.double.interpolated.pycee", fmt=True),
                string(r"[fF]'", "'", "string.quoted.single.interpolated.pycee", fmt=True),
                string(r'[rR]"', '"', "string.quoted.double.raw.pycee", escapes=False),
                string(r"[rR]'", "'", "string.quoted.single.raw.pycee", escapes=False),
                string('"', '"', "string.quoted.double.pycee"),
                string("'", "'", "string.quoted.single.pycee"),
            ]
        },
        "numbers": {
            "patterns": [
                {"name": "constant.numeric.hex.pycee", "match": r"\b0[xX][0-9A-Fa-f](?:_?[0-9A-Fa-f])*\b"},
                {"name": "constant.numeric.binary.pycee", "match": r"\b0[bB][01](?:_?[01])*\b"},
                {"name": "constant.numeric.octal.pycee", "match": r"\b0[oO][0-7](?:_?[0-7])*\b"},
                {"name": "constant.numeric.float.pycee",
                 "match": r"\b\d(?:_?\d)*(?:\.\d(?:_?\d)*(?:[eE][-+]?\d+)?|[eE][-+]?\d+)\b"},
                {"name": "constant.numeric.integer.pycee", "match": r"\b\d(?:_?\d)*\b"},
            ]
        },
        "keywords": {
            "patterns": [
                {"name": "keyword.control.flow.pycee",
                 "match": words(["if", "elif", "else", "while", "for", "do", "switch", "case",
                                 "default", "break", "continue", "return", "try", "except",
                                 "finally", "raise", "assert"])},
                {"name": "keyword.control.import.pycee", "match": words(["import", "from", "as"])},
                {"name": "storage.type.pycee",
                 "match": words(["func", "prog", "obj", "var", "vemp", "const"])},
                {"name": "storage.modifier.pycee", "match": words(["private", "static", "extends"])},
                {"name": "keyword.operator.logical.pycee",
                 "match": words(["and", "or", "xor", "not", "is", "in"])},
                {"name": "constant.language.pycee", "match": words(["true", "false", "none"])},
                {"name": "variable.language.pycee", "match": words(["self", "super"])},
                {"name": "keyword.other.reserved.pycee",
                 "match": words(["enum", "match", "async", "await", "export", "with", "man"])},
            ]
        },
        "builtins": {
            "patterns": [
                {"name": "support.type.exception.pycee", "match": words(errors)},
                {"name": "support.function.builtin.pycee",
                 "match": words(functions) + r"(?=\s*\()"},
                {"name": "entity.name.namespace.pycee",
                 "match": words(modules) + r"(?=\s*\.)"},
            ]
        },
        "calls": {
            "patterns": [
                {
                    "match": r"(\.)\s*([A-Za-z_]\w*)\s*(?=\()",
                    "captures": {
                        "1": {"name": "punctuation.accessor.pycee"},
                        "2": {"name": "entity.name.function.method.pycee"},
                    },
                },
                {
                    "match": r"\b([A-Za-z_]\w*)\s*(?=\()",
                    "captures": {"1": {"name": "entity.name.function.call.pycee"}},
                },
                {
                    "match": r"(\.)\s*([A-Za-z_]\w*)",
                    "captures": {
                        "1": {"name": "punctuation.accessor.pycee"},
                        "2": {"name": "variable.other.property.pycee"},
                    },
                },
            ]
        },
        "operators": {
            "patterns": [
                {"name": "storage.type.function.arrow.pycee", "match": r"=>"},
                {"name": "keyword.operator.spread.pycee", "match": r"\.\.\."},
                {"name": "keyword.operator.assignment.compound.pycee",
                 "match": r"(\+|-|\*|//|/|%|&|\||\^|<<|>>)="},
                {"name": "keyword.operator.increment.pycee", "match": r"\+\+|--"},
                {"name": "keyword.operator.comparison.pycee", "match": r"<=|>=|<|>"},
                {"name": "keyword.operator.bitwise.pycee", "match": r"<<|>>|&|\||\^|~"},
                {"name": "keyword.operator.arithmetic.pycee", "match": r"//|\+|-|\*|/|%"},
                {"name": "keyword.operator.assignment.pycee", "match": r"="},
                {"name": "keyword.operator.ternary.pycee", "match": r"\?|:"},
                {"name": "invalid.illegal.operator.pycee", "match": r"==|!=|!"},
                {"name": "keyword.other.reserved.pycee", "match": r"@"},
            ]
        },
        "punctuation": {
            "patterns": [
                {"name": "punctuation.terminator.statement.pycee", "match": ";"},
                {"name": "punctuation.separator.comma.pycee", "match": ","},
            ]
        },
    },
}

out = os.path.join(ROOT, "editors/vscode/syntaxes/pycee.tmLanguage.json")
with open(out, "w") as f:
    json.dump(grammar, f, indent=2)
    f.write("\n")
print("wrote", os.path.relpath(out, ROOT), f"({len(functions)} natives, {len(errors)} error types, {len(modules)} modules)")
