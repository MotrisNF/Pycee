#!/usr/bin/env python3
"""Writes src/types/unicode_data.c: the Unicode tables pycee needs.

Run it from the root of the project (python3 -I tools/gen_unicode.py) to
regenerate the file with the Unicode version of the Python in use. The
tables are ranges, searched by binary search: letters (Python's
str.isalpha), whitespace (str.isspace), decimal digits (str.isdecimal)
and the simple case mappings (a character that changes into exactly one
other one; "ß".upper() stays "ß").
"""

import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out = []
    start = None
    for c in range(MAX):
        if 0xD800 <= c <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(c))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def case_runs(fn):
    """(lo, hi, delta, step): every step-th character of [lo, hi] maps to
    itself + delta. step is 1 for blocks, 2 for alternating pairs."""
    maps = []
    for c in range(MAX):
        if 0xD800 <= c <= 0xDFFF:
            continue
        m = fn(chr(c))
        if len(m) == 1 and ord(m) != c:
            maps.append((c, ord(m) - c))
    runs = []
    for c, d in maps:
        if runs:
            lo, hi, delta, step = runs[-1]
            if delta == d:
                if step == 0 and c - hi in (1, 2):
                    runs[-1] = (lo, c, d, c - hi)
                    continue
                if step and c - hi == step:
                    runs[-1] = (lo, c, d, step)
                    continue
        runs.append((c, c, d, 0))
    return [(lo, hi, d, step or 1) for lo, hi, d, step in runs]


def emit_ranges(name, rs):
    lines = ["static const t_urange   %s[] = {" % name]
    for lo, hi in rs:
        lines.append("    {0x%X, 0x%X}," % (lo, hi))
    lines.append("};")
    return "\n".join(lines)


def emit_cases(name, rs):
    lines = ["static const t_ucase    %s[] = {" % name]
    for lo, hi, d, step in rs:
        lines.append("    {0x%X, 0x%X, %d, %d}," % (lo, hi, d, step))
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "/*",
        " * Generated by tools/gen_unicode.py from Unicode %s (do not edit by"
        % unicodedata.unidata_version,
        " * hand: run the script again). Ranges of code points, sorted.",
        " */",
        "",
        '#include <stddef.h>',
        '#include "types/unicode.h"',
        "",
        "typedef struct s_urange",
        "{",
        "    int32_t lo;",
        "    int32_t hi;",
        "}   t_urange;",
        "",
        "/* Every step-th character of [lo, hi] maps to itself + delta. */",
        "typedef struct s_ucase",
        "{",
        "    int32_t lo;",
        "    int32_t hi;",
        "    int32_t delta;",
        "    int32_t step;",
        "}   t_ucase;",
        "",
        emit_ranges("g_alpha", ranges(str.isalpha)),
        "",
        emit_ranges("g_space", ranges(str.isspace)),
        "",
        emit_ranges("g_digit", ranges(str.isdecimal)),
        "",
        emit_cases("g_upper", case_runs(str.upper)),
        "",
        emit_cases("g_lower", case_runs(str.lower)),
        "",
        BODY,
    ]
    with open("src/types/unicode_data.c", "w") as f:
        f.write("\n".join(parts))
    return 0


BODY = r"""#define COUNT(t) (sizeof(t) / sizeof(*(t)))

static int  in_ranges(const t_urange *t, size_t n, int32_t cp)
{
    size_t  lo;
    size_t  hi;
    size_t  mid;

    lo = 0;
    hi = n;
    while (lo < hi)
    {
        mid = lo + (hi - lo) / 2;
        if (cp < t[mid].lo)
            hi = mid;
        else if (cp > t[mid].hi)
            lo = mid + 1;
        else
            return (1);
    }
    return (0);
}

static int32_t  map_case(const t_ucase *t, size_t n, int32_t cp)
{
    size_t  lo;
    size_t  hi;
    size_t  mid;

    lo = 0;
    hi = n;
    while (lo < hi)
    {
        mid = lo + (hi - lo) / 2;
        if (cp < t[mid].lo)
            hi = mid;
        else if (cp > t[mid].hi)
            lo = mid + 1;
        else if ((cp - t[mid].lo) % t[mid].step == 0)
            return (cp + t[mid].delta);
        else
            return (cp);
    }
    return (cp);
}

int uni_is_alpha(int32_t cp)
{
    return (in_ranges(g_alpha, COUNT(g_alpha), cp));
}

int uni_is_space(int32_t cp)
{
    return (in_ranges(g_space, COUNT(g_space), cp));
}

int uni_is_digit(int32_t cp)
{
    return (in_ranges(g_digit, COUNT(g_digit), cp));
}

int32_t uni_upper(int32_t cp)
{
    return (map_case(g_upper, COUNT(g_upper), cp));
}

int32_t uni_lower(int32_t cp)
{
    return (map_case(g_lower, COUNT(g_lower), cp));
}
"""

if __name__ == "__main__":
    sys.exit(main())
